test('streams current weather before forecast and keeps search usable during loading', async ({ page, provider }, info) => {
  await provider.mode('forecast-valid', 3000)
  await page.goto('/ru/moscow', { waitUntil: 'commit' })
  await expect(page.getByRole('main').getByText('20°C', { exact: true })).toBeVisible()
  const forecast = page.getByRole('region', { name: 'Three-hour forecast' })
  await expect(forecast.getByRole('status')).toHaveText('Loading forecast...')
  const daily = page.getByRole('region', { name: 'Daily forecast', exact: true })
  await expect(daily.getByRole('status')).toHaveText('Loading daily forecast...')
  const input = page.getByRole('combobox')
  await input.fill('Suzhou')
  await expect(page.getByRole('option')).toHaveCount(2)
  await input.press('Escape')
  const list = forecast.getByRole('list')
  await expect(list.getByRole('listitem')).toHaveCount(8)
  await expect(list.getByText('Now', { exact: true })).toBeVisible()
  const timestamps = await list
    .locator('time')
    .evaluateAll((times) => times.map((time) => Date.parse(time.getAttribute('datetime') ?? '')))
  expect(timestamps).toHaveLength(7)
  const dailyRows = daily.getByRole('listitem')
  await expect.poll(() => dailyRows.count()).toBeGreaterThanOrEqual(5)
  expect(await dailyRows.count()).toBeLessThanOrEqual(6)
  const dates = await daily.locator('time').evaluateAll((times) => times.map((time) => time.getAttribute('datetime')))
  expect(new Set(dates).size).toBe(dates.length)
  expect(dates).toEqual([...dates].sort())
  expect(timestamps.slice(1).every((time, index) => time - timestamps[index] === 10800000)).toBe(true)
  if (info.project.name === 'mobile-chromium') {
    expect(await list.evaluate((element) => element.scrollWidth > element.clientWidth)).toBe(true)
    await list.focus()
    await list.press('ArrowRight')
    await expect.poll(() => list.evaluate((element) => element.scrollLeft)).toBeGreaterThan(0)
  }
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('retries a failed forecast while preserving current weather and search input', async ({ page, provider }) => {
  await provider.mode('forecast-http-503')
  await page.goto('/ru/moscow')
  const forecast = page.getByRole('region', { name: 'Three-hour forecast' })
  await expect(forecast.getByRole('alert')).toHaveText('Forecast is temporarily unavailable.')
  const daily = page.getByRole('region', { name: 'Daily forecast', exact: true })
  await expect(daily.getByRole('alert')).toHaveText('Daily forecast is temporarily unavailable.')
  await expect(page.getByRole('main').getByText('20°C', { exact: true })).toBeVisible()
  const input = page.getByRole('combobox')
  await input.fill('Suzhou')
  await expect(page.getByRole('option')).toHaveCount(2)
  await input.press('Tab')
  const retry = forecast.getByRole('button', { name: 'Try again' })
  await expect(retry).toBeFocused()
  await provider.mode('valid', 500)
  await retry.click()
  await expect(forecast.getByRole('listitem')).toHaveCount(8)
  await expect(daily.getByRole('list')).toBeVisible()
  await expect(input).toHaveValue('Suzhou')
  await expect(page.getByRole('main').getByText('20°C', { exact: true })).toBeVisible()
  expect((await provider.state()).requests.filter((request) => request.endpoint === '/data/2.5/weather')).toHaveLength(1)
})

test('contains unexpected forecast errors inside the timeline and recovers', async ({ page, provider }) => {
  await provider.mode('forecast-unexpected')
  await page.goto('/ru/moscow')
  const forecast = page.getByRole('region', { name: 'Three-hour forecast' })
  await expect(forecast.getByRole('alert')).toHaveText('Forecast could not be displayed. Try again.')
  const daily = page.getByRole('region', { name: 'Daily forecast', exact: true })
  await expect(daily.getByRole('alert')).toHaveText('Daily forecast could not be displayed. Try again.')
  await expect(page.getByRole('heading', { level: 1, name: 'Moscow, RU', exact: true })).toBeVisible()
  await expect(page.getByRole('main').getByText('20°C', { exact: true })).toBeVisible()
  await expect(page.getByRole('main')).not.toContainText('Private unexpected failure')
  await page.evaluate(() => {
    document.documentElement.dataset.forecastSession = 'preserved'
  })
  await provider.mode('valid')
  await forecast.getByRole('button', { name: 'Try again' }).click()
  await expect(forecast.getByRole('listitem')).toHaveCount(8)
  await expect(daily.getByRole('list')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.dataset.forecastSession)).toBe('preserved')
})

test('keeps weather and metric positions stable through both loading stages', async ({ page, provider }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await provider.mode('valid', 2000)
  await page.goto('/ru/moscow', { waitUntil: 'commit' })
  const loading = page.getByRole('status', { name: 'Loading weather...', exact: true })
  await expect(loading).toBeVisible()
  await expect(loading.locator('section[aria-label="Current weather"]')).toBeVisible()
  await expect(loading.locator('section[aria-label="Weather details"]')).toBeVisible()
  await page.evaluate(() => document.fonts.ready)
  const geometry = await page.waitForFunction(() => {
    const root = document.querySelector('[role="status"][aria-label="Loading weather..."]')
    const hero = root?.querySelector('section[aria-label="Current weather"]')?.getBoundingClientRect()
    const metrics = root?.querySelector('section[aria-label="Weather details"]')?.getBoundingClientRect()
    return hero?.height && metrics?.height
      ? { hero: { height: hero.height }, metrics: { y: metrics.y, height: metrics.height } }
      : null
  })
  const initial = await geometry.jsonValue()
  if (!initial) throw new Error('Loading layout was not measured')
  const { hero: heroBefore, metrics: metricsBefore } = initial
  expect(
    await loading
      .locator('span[style]')
      .first()
      .evaluate((element) => getComputedStyle(element).animationName)
  ).toBe('none')
  await expect(page.getByRole('combobox')).toBeEnabled()
  const hero = page.getByRole('region', { name: 'Current weather', exact: true })
  await expect(hero).toBeVisible()
  await expect(loading).toHaveCount(0)
  const metrics = page.getByRole('region', { name: 'Weather details', exact: true })
  const heroDuring = await hero.boundingBox()
  const metricsDuring = await metrics.boundingBox()
  expect(Math.abs(heroDuring!.height - heroBefore!.height)).toBeLessThan(2)
  expect(Math.abs(metricsDuring!.y - metricsBefore!.y)).toBeLessThan(2)
  expect(Math.abs(metricsDuring!.height - metricsBefore!.height)).toBeLessThan(2)
  await expect(hero.getByRole('listitem')).toHaveCount(8)
  await expect(page.getByRole('region', { name: 'Daily forecast', exact: true }).getByRole('list')).toBeVisible()
  expect(await hero.getByRole('list').evaluate((element) => getComputedStyle(element).animationName)).toBe('none')
  const heroAfter = await hero.boundingBox()
  const metricsAfter = await metrics.boundingBox()
  expect(Math.abs(heroAfter!.height - heroBefore!.height)).toBeLessThan(2)
  expect(Math.abs(metricsAfter!.y - metricsBefore!.y)).toBeLessThan(2)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
